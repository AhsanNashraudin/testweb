const csv = readFileSync(join(__dirname, 'data/price-list.csv'), 'utf8').trim().split('\n').slice(1).map((l) => l.split(','));
export const PRICES: Record<string, { price: number; bulk: number }> = Object.fromEntries(
  csv.map(([, code, price, bulk]) => [code.trim(), { price: Number(price), bulk: Number(bulk || 0) }]),
);
const BULK_MIN = 5; // "5 ใบขึ้นไป"

export type V = { name: string; sku: string; price: number; bulkPrice: number; bulkMinQty: number; stock: number; weightKg: number };
export type P = { slug: string; cat: string; name: string; brand?: string; short: string; desc: string; img: string; badge?: string; featured?: boolean; specs?: string; v: V[] };

/** ตัวเลือกที่มีราคาใน Price List (ไม่พบรหัส = error ทันที กันพิมพ์ผิด) */
const priced = (name: string, sku: string, priceKey = sku, weightKg = 0): V => {
  const p = PRICES[priceKey];
  if (!p) throw new Error(`ไม่พบรหัส ${priceKey} ใน price-list.csv`);
  return { name, sku, price: p.price, bulkPrice: p.bulk, bulkMinQty: p.bulk ? BULK_MIN : 0, stock: 100, weightKg };
};
